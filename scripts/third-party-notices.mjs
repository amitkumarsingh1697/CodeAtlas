#!/usr/bin/env node
// LIC-001: writes THIRD_PARTY_NOTICES.md at the repository root from the installed production
// dependency tree (`pnpm list --prod`), reading each package's own package.json and its LICENSE
// and NOTICE files from node_modules. No network access.
//   node scripts/third-party-notices.mjs          write the file
//   node scripts/third-party-notices.mjs --check  exit 1 if the file is out of date
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, runtimeDependencies } from './lib/runtime-deps.mjs';

const OUT = join(ROOT, 'THIRD_PARTY_NOTICES.md');
const COPYLEFT = /\b(A?GPL|LGPL|MPL|EPL|CDDL|EUPL|SSPL|CC-BY-SA)/u;
const PERMISSIVE =
  /^(\(?(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|Unlicense|CC0-1\.0|Python-2\.0)\)?( (OR|AND) )?)+$/u;

const { pkgs, platformOnly } = runtimeDependencies();

const cell = (s) => String(s).replaceAll('|', '\\|');
const flagged = pkgs.filter((p) => COPYLEFT.test(p.license) || !PERMISSIVE.test(p.license));
const lines = [
  '# Third-party notices',
  '',
  'CodeAtlas and ArchLens are licensed under the Apache License 2.0 (see `LICENSE` and `NOTICE`). They use the open-source packages below at run time. This list is generated by `node scripts/third-party-notices.mjs` from the installed production dependencies of every workspace package (`pnpm list --prod`), and CI checks that it is current. Development-only tools (test runners, linters, bundlers) are not listed because they are not part of what runs.',
  '',
  "Each package's full licence text is in its own folder under `node_modules` and in its published package. The ArchLens bundle ships its own `skills/archlens/scripts/brain/THIRD-PARTY-LICENSES.txt` with the full texts of what it bundles. The tree-sitter grammars are WebAssembly files in `packages/syntax/grammars`, not npm packages: each has its licence beside it (`<name>.LICENSE`) and its source and commit in `MANIFEST.json`.",
  '',
  `${pkgs.length} packages.${flagged.length ? ` Not a common permissive licence, to review: ${flagged.map((p) => `${p.name} (${p.license})`).join(', ')}.` : ' All use a common permissive licence (MIT, ISC, BSD, Apache-2.0 or similar).'}`,
  '',
  ...(platformOnly.length
    ? [
        `Installed only on some operating systems, so not read here: ${platformOnly.join(', ')}.`,
        '',
      ]
    : []),
  '| Package | Version | Licence | Source | Licence file |',
  '| --- | --- | --- | --- | --- |',
  ...pkgs.map(
    (p) =>
      `| ${cell(p.name)} | ${cell(p.version)} | ${cell(p.license)} | ${cell(p.repository || '—')} | ${cell(p.licenseFiles.join(', ') || 'none in package')} |`,
  ),
  '',
];
const withNotice = pkgs.filter((p) => p.notices.length);
if (withNotice.length) {
  lines.push('## NOTICE files', '', 'Reproduced as Apache License 2.0 §4(d) asks.', '');
  for (const p of withNotice)
    lines.push(`### ${p.name} ${p.version}`, '', '```text', ...p.notices, '```', '');
}
// Formatted as the repository formats Markdown, so `pnpm format:check` and `--check` agree.
const prettier = await import('prettier');
const text = await prettier.format(lines.join('\n'), {
  ...(await prettier.resolveConfig(OUT)),
  filepath: OUT,
});

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    process.stderr.write(
      'THIRD_PARTY_NOTICES.md is out of date: run node scripts/third-party-notices.mjs\n',
    );
    process.exit(1);
  }
  process.stdout.write(`THIRD_PARTY_NOTICES.md is current (${pkgs.length} packages).\n`);
} else {
  writeFileSync(OUT, text);
  process.stdout.write(
    `Wrote THIRD_PARTY_NOTICES.md: ${pkgs.length} packages, ${flagged.length} to review.\n`,
  );
}
